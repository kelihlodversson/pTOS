/* Stable enumeration and bounded peer metadata use session identities. */
static int peer_checks(void)
{
    LONG first_handle, second_handle, replacement;
    LONG first_window, second_window, other_window;
    run = &first; first_handle = cuis_service(CUIS_SESSION_START,0);
    run = &second; second_handle = cuis_service(CUIS_SESSION_START,0);
    CHECK(cuis_peer_service(CUIS_PEER_NEXT,first_handle,~0ULL,0,0,0) == EACCDN);
    CHECK(cuis_peer_service(CUIS_PEER_NEXT,second_handle,~0ULL,0,0,0) == first_handle);
    CHECK(cuis_peer_service(CUIS_PEER_NEXT,second_handle,first_handle,0,0,0) == second_handle);
    CHECK(cuis_peer_service(CUIS_PEER_NEXT,second_handle,second_handle,0,0,0) == EFILNF);
    CHECK(cuis_peer_service(CUIS_PEER_NEXT,second_handle,0x100000000ULL,0,0,0) == EINVAL);
    CHECK(cuis_peer_service(CUIS_SESSION_TAG,second_handle,0x80000000ULL,0,0,0) == EINVAL);
    CHECK(cuis_peer_service(CUIS_SESSION_TAG,second_handle,0x1234,0,0,0) == E_OK);
    CHECK(cuis_peer_service(CUIS_PEER_QUERY,second_handle,second_handle,CUIS_PEER_TAG,0,0) == 0x1234);
    memcpy(stream_input,"SECOND  ",8);
    CHECK(cuis_directory_service(CUIS_SESSION_LABEL,second_handle,0x10000,8) == E_OK);
    run = &first;
    CHECK(cuis_peer_service(CUIS_PEER_QUERY,first_handle,second_handle,CUIS_PEER_LABEL,0x20000,7) == ERANGE);
    CHECK(cuis_peer_service(CUIS_PEER_QUERY,first_handle,second_handle,CUIS_PEER_LABEL,0x20000,32) == 8);
    CHECK(!memcmp(stream_output,"SECOND  ",8));
    CHECK(cuis_peer_service(CUIS_PEER_QUERY,first_handle,second_handle,CUIS_PEER_TAG,0,0) == 0x1234);
    CHECK(cuis_peer_service(CUIS_PEER_QUERY,first_handle,second_handle,CUIS_PEER_STATE,0,0) == 0);
    CHECK(cuis_peer_service(CUIS_PEER_QUERY,first_handle,0,CUIS_PEER_BACKGROUND,0,0) == EFILNF);
    first_window = cuis_window_service(CUIS_WINDOW_CREATE,0,0,30,30,0);
    CHECK(first_window >= 0 && cuis_window_service(CUIS_WINDOW_SHOW,first_window,0,0,0,0) == E_OK);
    run = &second;
    second_window = cuis_window_service(CUIS_WINDOW_CREATE,0,0,30,30,0);
    other_window = cuis_window_service(CUIS_WINDOW_CREATE,0,0,30,30,0);
    CHECK(cuis_window_service(CUIS_WINDOW_SHOW,second_window,0,0,0,0) == E_OK);
    CHECK(cuis_window_service(CUIS_WINDOW_SHOW,other_window,0,0,0,0) == E_OK);
    run = &first;
    CHECK(cuis_window_service(CUIS_WINDOW_RAISE,first_window,0,0,0,0) == E_OK);
    CHECK(cuis_peer_service(CUIS_PEER_RAISE,first_handle,second_handle,0,0,0) == E_OK);
    CHECK(window_front->handle == (ULONG)other_window && window_front->znext->handle == (ULONG)second_window);
    CHECK(window_front->znext->znext->handle == (ULONG)first_window && focus_window == window_front);
    CHECK(cuis_peer_service(CUIS_PEER_QUERY,first_handle,0,CUIS_PEER_ACTIVE,0,0) == second_handle);
    CHECK(cuis_window_service(CUIS_WINDOW_HIDE,first_window,0,0,0,0) == E_OK);
    CHECK(cuis_peer_service(CUIS_PEER_RAISE,first_handle,first_handle,0,0,0) == E_OK);
    CHECK(!focus_window && windowless_focus && windowless_focus->handle == (ULONG)first_handle);
    CHECK(cuis_keyboard_event(0x1e0061));
    CHECK(cuis_session_wait(first_handle,0,CUIS_READY_KEY|CUIS_READY_TIMER,0) & CUIS_READY_KEY);
    CHECK(cuis_display_lock(first_handle,1,0) == E_OK);
    CHECK(cuis_background(first_handle,1) == E_OK);
    CHECK(cuis_surface_service(CUIS_SURFACE_REGISTER,first_handle,20) == E_OK);
    CHECK(cuis_display_lock(first_handle,0,0) == E_OK);
    CHECK(cuis_peer_service(CUIS_PEER_QUERY,first_handle,first_handle,CUIS_PEER_STATE,0,0) ==
          (CUIS_PEER_HAS_SURFACE|CUIS_PEER_HAS_BACKGROUND));
    CHECK(cuis_peer_service(CUIS_PEER_QUERY,first_handle,0,CUIS_PEER_BACKGROUND,0,0) == first_handle);
    /* A caller may own the display while activating a windowless menu client.
     * Releasing that lock must not put the desktop menu over the client's keys. */
    run = &second;
    CHECK(cuis_display_lock(second_handle,1,0) == E_OK);
    CHECK(cuis_surface_service(CUIS_SURFACE_REGISTER,second_handle,20) == E_OK);
    CHECK(cuis_display_lock(second_handle,0,0) == E_OK);
    CHECK(cuis_window_service(CUIS_WINDOW_HIDE,other_window,0,0,0,0) == E_OK);
    CHECK(cuis_window_service(CUIS_WINDOW_HIDE,second_window,0,0,0,0) == E_OK);
    run = &first;
    CHECK(cuis_display_lock(first_handle,1,0) == E_OK);
    CHECK(cuis_peer_service(CUIS_PEER_RAISE,first_handle,second_handle,0,0,0) == E_OK);
    CHECK(surface_focus_pending && windowless_focus->handle == (ULONG)second_handle);
    CHECK(cuis_display_lock(first_handle,0,0) == E_OK);
    CHECK(surface_owner && surface_owner->handle == (ULONG)second_handle && !surface_focus_pending);
    CHECK(cuis_keyboard_event(0x1e0061));
    run = &second;
    CHECK(cuis_session_wait(second_handle,0,CUIS_READY_KEY|CUIS_READY_TIMER,0) & CUIS_READY_KEY);
    run = &first;
    region_exit_on_output = TRUE;
    CHECK(cuis_peer_service(CUIS_PEER_QUERY,first_handle,second_handle,CUIS_PEER_LABEL,0x20000,32) == EIMBA);
    CHECK(!*find_owner(&first));
    replacement = cuis_service(CUIS_SESSION_START,0);
    CHECK(replacement > second_handle);
    CHECK(cuis_peer_service(CUIS_PEER_NEXT,replacement,first_handle,0,0,0) == second_handle);
    cuis_process_exit(&second);
    CHECK(cuis_peer_service(CUIS_PEER_QUERY,replacement,second_handle,CUIS_PEER_LABEL,0x20000,32) == EFILNF);
    CHECK(cuis_peer_service(CUIS_PEER_NEXT,replacement,second_handle,0,0,0) == replacement);
    cuis_process_exit(&first);
    CHECK(!cuis_session_count() && allocations == frees && input_irqs);
    return 0;
}
